package seoultech.se.tetris.versus.p2p;

/**
 * P2P 연결 상태. 0.5초마다 주고받는 확인 신호로 판정한다. (3차 팀 결정)
 *
 * <p>위에서 아래로 나빠지는 순서이며, 여러 조건에 해당하면 가장 나쁜 상태로 본다.
 * 연결 끊김으로 판정되기 전까지 플레이어 자신의 게임은 정상적으로 진행한다.
 */
public enum ConnectionState {

    /** 최근 10회 왕복 시간의 평균이 300ms 미만 */
    NORMAL,

    /** 최근 10회 왕복 시간의 평균이 300ms 이상이거나, 마지막 신호를 받은 지 1초가 지남 */
    LAGGING,

    /** 마지막 신호를 받은 지 3초가 지남 */
    CHECKING,

    /** 마지막 신호를 받은 지 10초가 지났거나, 상대가 직접 연결을 끊음 */
    DISCONNECTED
}
