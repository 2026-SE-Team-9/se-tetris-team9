package seoultech.se.tetris.versus;

/**
 * 대전이 끝난 사유. 대전 모드의 종료 화면에 표시한다. (3차 팀 결정)
 *
 * <p>로컬 대전 도중 게임을 종료한 경우와 P2P 연결이 끊긴 경우는 결과 없이 끝나므로 사유가 없다.
 */
public enum EndReason {

    /** 블럭을 더 이상 쌓을 수 없게 됨. 공격 줄에 밀려 보드 위로 칸이 넘친 경우를 포함한다. */
    TOP_OUT,

    /** 시간제한 모드의 제한 시간이 끝남 */
    TIME_UP,

    /** P2P 대전 모드에서 상대가 게임 나가기를 선택함 */
    FORFEIT
}
